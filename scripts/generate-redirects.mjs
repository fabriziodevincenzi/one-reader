import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const contentRoot = new URL('../src/content/journal/', import.meta.url);
const redirectsFile = new URL('../public/_redirects', import.meta.url);

const readFrontmatterField = (source, field) => {
  const value = source.match(new RegExp(`^${field}:\\s*(.+?)\\s*$`, 'm'))?.[1]?.trim();
  return value?.replace(/^(['"])(.*)\1$/, '$2');
};

const articles = readdirSync(contentRoot, { withFileTypes: true }).flatMap((localeDirectory) => {
  if (!localeDirectory.isDirectory()) return [];
  const localeRoot = new URL(`${localeDirectory.name}/`, contentRoot);

  return readdirSync(localeRoot, { withFileTypes: true }).flatMap((entry) => {
    if (!entry.isFile() || !entry.name.endsWith('.md')) return [];
    const source = readFileSync(new URL(entry.name, localeRoot), 'utf8');
    const slug = readFrontmatterField(source, 'slug');
    const key = readFrontmatterField(source, 'key');
    if (!slug) throw new Error(`Missing slug in ${join(localeDirectory.name, entry.name)}`);
    if (!key) throw new Error(`Missing translation key in ${join(localeDirectory.name, entry.name)}`);

    return [{
      locale: localeDirectory.name,
      slug,
      key,
      fileSlug: basename(entry.name, '.md'),
    }];
  });
});

const articlePath = (locale, slug) => `${locale === 'en' ? '' : `/${locale}`}/journal/${slug}/`;
const canonicalPaths = new Set(articles.map(({ locale, slug }) => articlePath(locale, slug)));
const redirects = new Map([
  ['/blog/', '/journal/'],
  ['/blog/what-an-inbox-can-still-be-for/', '/journal/what-an-inbox-can-still-be-for/'],
  ['/waitlist/', '/'],
]);

for (const article of articles) {
  const target = articlePath(article.locale, article.slug);
  for (const legacySlug of new Set([article.key, article.fileSlug])) {
    const source = articlePath(article.locale, legacySlug);
    if (source === target) continue;
    if (canonicalPaths.has(source)) throw new Error(`Redirect source is canonical: ${source}`);
    const existingTarget = redirects.get(source);
    if (existingTarget && existingTarget !== target) {
      throw new Error(`Conflicting redirects for ${source}: ${existingTarget} and ${target}`);
    }
    redirects.set(source, target);
  }
}

const lines = [
  '# Generated by scripts/generate-redirects.mjs. Do not edit by hand.',
  ...[...redirects.entries()]
    .sort(([sourceA], [sourceB]) => sourceA.localeCompare(sourceB))
    .map(([source, target]) => `${encodeURI(source)} ${encodeURI(target)} 301`),
  '',
];

writeFileSync(redirectsFile, lines.join('\n'));
console.log(`Generated ${redirects.size} permanent redirects.`);
